    @click="emit('click', $event)"
  >
    <title v-if="props.title">{{ props.title }}</title>
    <path d="M24.008 41.99a.01.01 0 0 1-.016 0l-9.978-11.974A.01.01 0 0 1 14.02 30H33.98a.01.01 0 0 1 .007.016z" />
