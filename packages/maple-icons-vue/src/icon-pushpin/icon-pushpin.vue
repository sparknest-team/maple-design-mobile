      d="M19.921 28.163 7.193 40.89m12.728-12.728 8.884 8.883c.17.17.447.17.617 0l5.12-5.12a7.86 7.86 0 0 0 1.667-8.655.09.09 0 0 1 .02-.102l4.906-4.906a2 2 0 0 0 0-2.828L32.649 6.95a2 2 0 0 0-2.828 0l-4.89 4.889a.13.13 0 0 1-.139.027 7.83 7.83 0 0 0-8.618 1.66l-5.027 5.026a.59.59 0 0 0 0 .836z"
